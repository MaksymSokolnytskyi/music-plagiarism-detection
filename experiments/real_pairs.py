"""Rebuilt features vs the v3 CNN on the same 27 real, unseen pairs.

Question: on the exact pairs where the Siamese CNN scored AUC 0.47 (embedding cosine)
and 0.59 (classifier head), how do the training-free features do?

The features have no trainable parameters and use the default configuration chosen
before this experiment, so every pair is a test pair; nothing was tuned on these 27.
Audio is copyrighted and not in the repository: pass ``--audio-dir`` pointing at a
folder holding ``original/*.wav`` and ``comparison/*.wav`` (the hackathon excerpts).
Writes ``results/real/scores.csv`` and ``results/real/REPORT.md``.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import time
from pathlib import Path

import numpy as np

from musicplag import metrics, spectral
from musicplag.config import CONFIG
from musicplag.data import normalize_title
from musicplag.features import DEFAULT_FEATURES, PairContext, analyze_pair

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "results" / "history" / "v3_cnn_unseen.csv"
CNN_HEAD = ROOT / "results" / "history" / "v3_cnn_head_unseen.csv"
OUT = ROOT / "results" / "real"
SEED = 0


def _load(path: Path) -> np.ndarray:
    import librosa

    y, _ = librosa.load(path, sr=CONFIG.sample_rate, mono=True)
    assert len(y) > 4 * CONFIG.sample_rate, f"{path.name}: shorter than 4 s"
    return np.asarray(y, dtype=np.float64)


def _index(audio_dir: Path) -> dict[str, Path]:
    files = sorted(audio_dir.glob("*/*.wav"))
    index = {normalize_title(f.name): f for f in files}
    assert len(index) == len(files), "two files normalise to the same title"
    return index


def main() -> None:
    """Score all 27 pairs, compare with the CNN's saved scores, write the report."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--audio-dir", type=Path, required=True)
    parser.add_argument("--cache", type=Path, default=Path(".cache/cqt"))
    args = parser.parse_args()
    args.cache.mkdir(parents=True, exist_ok=True)
    index = _index(args.audio_dir)

    def cqt_of(title: str) -> np.ndarray:
        key = hashlib.sha1(title.encode("utf-8")).hexdigest()[:16]
        cached = args.cache / f"{key}.npy"  # str hash() is salted per process
        if cached.exists():
            return np.load(cached)
        mag = spectral.cqt(_load(index[title]), CONFIG)
        np.save(cached, mag)
        return mag

    with MANIFEST.open(encoding="utf-8") as fh:
        pairs = list(csv.DictReader(fh))
    with CNN_HEAD.open(encoding="utf-8") as fh:
        head = {r["pair"]: float(r["head_prob"]) for r in csv.DictReader(fh)}
    assert len(pairs) == 27, "expected the 27-pair unseen set"

    start, rows = time.time(), []
    for p in pairs:
        ctx = PairContext(cqt_of(p["original"]), cqt_of(p["suspect"]), CONFIG)
        report = analyze_pair(ctx)
        row: dict[str, object] = {
            "original": p["original"],
            "suspect": p["suspect"],
            "relation": p["relation"],
            "label": int(p["label"]),
            "transposition": report.transposition_semitones,
            "cnn_cosine": float(p["cnn_cosine_mean"]),
            "cnn_head": head[f"{p['original']} vs {p['suspect']}"],
        }
        row.update(report.features)
        rows.append(row)
        print(f"{len(rows)}/27 {p['relation']:8s} {p['original'][:30]}", flush=True)

    OUT.mkdir(parents=True, exist_ok=True)
    with (OUT / "scores.csv").open("w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(
            {k: (f"{v:.6f}" if isinstance(v, float) else v) for k, v in r.items()}
            for r in rows
        )

    y = [int(r["label"]) for r in rows]  # type: ignore[call-overload]
    names = ["cnn_cosine", "cnn_head", *(f.name for f in DEFAULT_FEATURES)]
    lines = [
        "# Real pairs: rebuilt features vs the v3 CNN",
        "",
        f"Generated by `experiments/real_pairs.py` ({time.time() - start:.0f} s). The 27 "
        "pairs the CNN was evaluated on as 'unseen tracks': 11 derived (6 plagiarism "
        "cases, 5 remakes) and 16 unrelated pairings, curated 9-53 s excerpts. The "
        "features were not tuned on these pairs. CNN scores are the ones v3 saved.",
        "",
        "| score | AUC | 95% CI | p (AUC>0.5) | Cohen's d |",
        "|---|---|---|---|---|",
    ]
    for name in names:
        s = metrics.summarize([float(r[name]) for r in rows], y, seed=SEED)  # type: ignore[arg-type]
        kind = "v3 CNN" if name.startswith("cnn") else "rebuilt"
        lines.append(
            f"| `{name}` ({kind}) | **{s.auc:.3f}** | [{s.ci_low:.2f}, {s.ci_high:.2f}] "
            f"| {s.p_value:.3f} | {s.cohens_d:+.2f} |"
        )
    lines += [
        "",
        "With 11 positives the interval half-width is about ±0.2: a feature needs an AUC "
        "near 0.75 before its lower bound clears 0.5. Read differences between rows "
        "as directions, not rankings. Five rebuilt features were tested: with a "
        "Bonferroni correction the significance level is "
        f"{0.05 / len(DEFAULT_FEATURES):.3f}, "
        "so no single p-value here is significant on its own. What the table supports: "
        "the order-aware harmonic features (`chroma_dtw`, `markov_js`) point the right "
        "way on unseen real pairs where the CNN did not, and the effect needs a larger "
        "pair set to be confirmed.",
        "",
    ]
    text = "\n".join(lines) + "\n"
    (OUT / "REPORT.md").write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
